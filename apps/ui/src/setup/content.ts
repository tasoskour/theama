import { SETUP_RESOURCES, type SetupResourceId } from '@theama/contracts'

export const WIZARD_STEPS = ['welcome', 'service', 'library', 'playback', 'metadata', 'subtitles', 'downloads', 'review'] as const
export type WizardStep = typeof WIZARD_STEPS[number]
export type GuideId = WizardStep | 'installation' | 'prowlarr' | 'vpn' | 'maintenance' | 'developer' | 'troubleshooting'
export type GuideBlock =
  | { kind: 'paragraph'; text: string }
  | { kind: 'steps'; items: string[] }
  | { kind: 'table'; headers: string[]; rows: string[][] }
  | { kind: 'code'; text: string }
  | { kind: 'links'; items: { resource: SetupResourceId; label: string }[] }
  | { kind: 'troubleshooting'; items: { symptom: string; solution: string }[] }
export interface GuideSection {
  id: GuideId
  title: string
  summary: string
  optional: boolean
  route?: string
  blocks: GuideBlock[]
}
export interface SetupGuide { title: string; intro: string; sections: GuideSection[] }

export const paragraph = (text: string): GuideBlock => ({ kind: 'paragraph', text })
export const steps = (...items: string[]): GuideBlock => ({ kind: 'steps', items })
export const code = (text: string): GuideBlock => ({ kind: 'code', text })
export const links = (...items: [SetupResourceId, string][]): GuideBlock => ({ kind: 'links', items: items.map(([resource, label]) => ({ resource, label })) })

export function searchableText(section: GuideSection): string {
  return JSON.stringify(section).normalize('NFD').replace(/\p{M}/gu, '').toLocaleLowerCase()
}

export function guideMarkdown(guide: SetupGuide): string {
  const prose = (value: string) => value.replaceAll('\\', '\\\\').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  const out = [`<!-- Generated by yarn docs:setup. Edit apps/ui/src/setup/guide.{en,el}.ts instead. -->`, `# ${guide.title}`, guide.intro,
    guide.sections.map((s) => `- [${s.title}](#${s.id})`).join('\n')]
  for (const section of guide.sections) {
    out.push(`<a id="${section.id}"></a>\n\n## ${section.title}`, section.summary)
    for (const block of section.blocks) {
      switch (block.kind) {
        case 'paragraph': out.push(prose(block.text)); break
        case 'steps': out.push(block.items.map((item, i) => `${i + 1}. ${prose(item)}`).join('\n')); break
        case 'code': out.push(`\`\`\`powershell\n${block.text}\n\`\`\``); break
        case 'links': out.push(block.items.map((item) => `- [${item.label}](${SETUP_RESOURCES[item.resource]})`).join('\n')); break
        case 'table': {
          const row = (cells: string[]) => `| ${cells.map((c) => c.replaceAll('|', '\\|').replaceAll('\n', '<br>')).join(' | ')} |`
          out.push([row(block.headers), row(block.headers.map(() => '---')), ...block.rows.map(row)].join('\n'))
          break
        }
        case 'troubleshooting': out.push(block.items.map((i) => `### ${i.symptom}\n\n${i.solution}`).join('\n\n')); break
      }
    }
  }
  return `${out.join('\n\n')}\n`
}
